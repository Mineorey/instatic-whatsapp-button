// Bundles server/lib/button.js + server/entry.js into one QuickJS-compatible
// file, writes dist/plugin.json and packs the installable zip.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { zipSync } from 'fflate'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const DIST = join(ROOT, 'dist')

rmSync(DIST, { recursive: true, force: true })
mkdirSync(join(DIST, 'server'), { recursive: true })

const strip = (src, keepExports) => src
  .split('\n').filter((l) => !/^\s*import\s/.test(l)).join('\n')
  .replace(keepExports ? /$^/ : /^export\s+(?=(const|function|async function|let|class)\b)/gm, '')

const bundle = '// filmorbit.whatsapp-button server bundle (generated by scripts/build.mjs)\n' +
  strip(readFileSync(join(ROOT, 'server/lib/button.js'), 'utf8'), false) +
  '\n' + strip(readFileSync(join(ROOT, 'server/entry.js'), 'utf8'), true)
writeFileSync(join(DIST, 'server/index.js'), bundle)

const manifest = JSON.parse(readFileSync(join(ROOT, 'plugin.base.json'), 'utf8'))
writeFileSync(join(DIST, 'plugin.json'), JSON.stringify(manifest, null, 2))

const files = {
  'plugin.json': readFileSync(join(DIST, 'plugin.json')),
  'server/index.js': readFileSync(join(DIST, 'server/index.js')),
  'frontend/contact-button.css': readFileSync(join(ROOT, 'frontend/contact-button.css')),
  'frontend/contact-button.js': readFileSync(join(ROOT, 'frontend/contact-button.js')),
  'icon.svg': readFileSync(join(ROOT, 'icon.svg')),
  'README.md': readFileSync(join(ROOT, 'README.md')),
  'LICENSE': readFileSync(join(ROOT, 'LICENSE')),
  'CHANGELOG.md': readFileSync(join(ROOT, 'CHANGELOG.md')),
}
writeFileSync(join(DIST, `${manifest.id}-${manifest.version}.zip`), zipSync(files))
console.log('built', Object.keys(files).length, 'files')
